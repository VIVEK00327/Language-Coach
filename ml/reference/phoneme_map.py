"""Phoneme normalization and token mapping. OWNER: Role 3 (R3-03).

Standardizes IPA representations between:
1. Reference phonemes generated by eSpeak NG (phonemizer)
2. Spoken phonemes emitted by acoustic models (wav2vec 2.0 / Whisper)

Normalization rules:
- Length marks (ː, :) are attached to the preceding vowel ('i' + 'ː' -> 'iː').
- Standard diphthongs (oʊ, aɪ, eɪ, aʊ, ɔɪ, ɪə, eə, ʊə) are grouped into a single unit.
- Common affricates (tʃ, dʒ) are grouped into a single unit.
- Stress marks (ˈ, ˌ, ', `) and whitespace are stripped.
- American flap /ɾ/ is preserved as a distinct symbol (aligned as similar to /t/ and /d/).
"""
import re
from typing import List, Union

# Standard English diphthongs
DIPHTHONGS = {"oʊ", "aɪ", "eɪ", "aʊ", "ɔɪ", "ɪə", "eə", "ʊə"}

# Affricates
AFFRICATES = {"tʃ", "dʒ", "tʃ", "dʒ"}

# Multi-character phonetic units
MULTI_CHAR_UNITS = DIPHTHONGS | AFFRICATES

# Characters to ignore (stress marks, tone, formatting)
STRESS_AND_IGNORED = set("ˈˌ'` \t\n\r.")

LENGTH_MARKS = {"ː", ":"}


def normalize_phonemes(phonemes: Union[str, List[str]]) -> List[str]:
    """Normalize a raw IPA string or phoneme list into unified phonetic units.

    Examples:
      "həˈloʊ"        -> ['h', 'ə', 'l', 'oʊ']
      "wˈɔːtə"        -> ['w', 'ɔː', 't', 'ə']
      ['s', 'i', 'ː'] -> ['s', 'iː']
      ['ʃ', 'ɪ', 'p'] -> ['ʃ', 'ɪ', 'p']
    """
    if isinstance(phonemes, str):
        # Extract individual characters, skipping stress and whitespace
        chars = [c for c in phonemes if c not in STRESS_AND_IGNORED]
    else:
        # Flatten and filter list of tokens
        chars = []
        for item in phonemes:
            if not item:
                continue
            for c in str(item):
                if c not in STRESS_AND_IGNORED:
                    chars.append(c)

    if not chars:
        return []

    tokens: List[str] = []
    i = 0
    n = len(chars)

    while i < n:
        c = chars[i]

        # 1. Check if length mark: attach to previous token if available
        if c in LENGTH_MARKS:
            if tokens:
                tokens[-1] = tokens[-1] + "ː"
            i += 1
            continue

        # 2. Check 2-character units (diphthongs, affricates)
        if i + 1 < n:
            pair = c + chars[i + 1]
            if pair in MULTI_CHAR_UNITS:
                # Also check if followed immediately by a length mark (e.g. pair + 'ː')
                if i + 2 < n and chars[i + 2] in LENGTH_MARKS:
                    tokens.append(pair + "ː")
                    i += 3
                else:
                    tokens.append(pair)
                    i += 2
                continue

        # 3. Single character: check if immediately followed by length mark
        if i + 1 < n and chars[i + 1] in LENGTH_MARKS:
            tokens.append(c + "ː")
            i += 2
            continue

        # 4. Standard single phone
        tokens.append(c)
        i += 1

    return tokens
